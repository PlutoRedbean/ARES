#!/usr/bin/env python3
# =============================================================================
# Self-test for the ARES configuration tool (scripts/kconfig/ares_kconfig.py)
# -----------------------------------------------------------------------------
#   python3 scripts/kconfig/test_kconfig.py        (or: make test-config)
#
# Covers: defaults, "set" (including range rejection), the .config <-> header
# generation, the savedefconfig/loaddefconfig round trip, the scripted line
# based menu, and a real curses session driven through a pty.  The repository
# configuration is restored to the defaults before the script returns.
# =============================================================================

import os
import re
import select
import subprocess
import sys
import time

sys.dont_write_bytecode = True  # keep the tree free of __pycache__

HERE = os.path.dirname(os.path.abspath(__file__))
ARES_HOME = os.path.abspath(os.path.join(HERE, os.pardir, os.pardir))
TOOL = os.path.join(HERE, "ares_kconfig.py")
DOT_CONFIG = os.path.join(ARES_HOME, "configs", "build", ".config")
DEFCONFIG = os.path.join(ARES_HOME, "configs", "defconfig")
AUTOCONF = os.path.join(ARES_HOME, "configs", "build", "vsrc", "include",
                        "ares_autoconf.vh")

FAILURES = []


def check(cond, message):
    if cond:
        print("  ok   : %s" % message)
    else:
        print("  FAIL : %s" % message)
        FAILURES.append(message)


def run(*args, stdin=None):
    return subprocess.run([sys.executable, TOOL, *args], input=stdin,
                          capture_output=True, text=True)


def read(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def test_defaults():
    print("defaults")
    run("defconfig")
    out = run("show").stdout
    check("CONFIG_MUL_LATENCY = 3" in out, "defconfig sets MUL_LATENCY = 3")
    check("CONFIG_LINE_BYTES = 32" in out, "defconfig sets LINE_BYTES = 32")
    header = read(AUTOCONF)
    check("CONFIG_MUL_LATENCY 3" in header, "header carries CONFIG_MUL_LATENCY")
    check("CONFIG_LINE_BYTES 32" in header, "header carries CONFIG_LINE_BYTES")


def test_set_and_range():
    print("set / range enforcement")
    run("set", "MUL_LATENCY=2", "LINE_BYTES=64")
    out = run("show").stdout
    check("CONFIG_MUL_LATENCY = 2" in out, "set MUL_LATENCY = 2")
    check("CONFIG_LINE_BYTES = 64" in out, "set LINE_BYTES = 64")
    check(re.search(r"CONFIG_LINE_BYTES 64", read(AUTOCONF)) is not None,
          "header regenerated by set")
    check("CONFIG_LINE_BYTES_64 = 1" in out, "selected choice member is emitted")

    bad = run("set", "MUL_LATENCY=5")
    check(bad.returncode != 0, "MUL_LATENCY=5 is rejected (range 2..3)")
    bad = run("set", "LINE_BYTES=48")
    check(bad.returncode != 0, "LINE_BYTES=48 is rejected (needs a choice member)")

    defs = run("defs").stdout
    check("-DCONFIG_MUL_LATENCY=2" in defs, "defs prints the Verilator -D flags")


def test_defconfig_roundtrip():
    print("savedefconfig / loaddefconfig")
    run("set", "MUL_LATENCY=2", "LINE_BYTES=16")
    run("savedefconfig")
    saved = read(DEFCONFIG)
    check("CONFIG_MUL_LATENCY=2" in saved, "defconfig stores the non-default MUL")
    check("CONFIG_LINE_BYTES_16=y" in saved, "defconfig stores the choice member")
    check("CONFIG_LINE_BYTES_32=n" not in saved, "defconfig stays minimal")

    run("defconfig")
    run("loaddefconfig")
    out = run("show").stdout
    check("CONFIG_MUL_LATENCY = 2" in out and "CONFIG_LINE_BYTES = 16" in out,
          "loaddefconfig restores the saved configuration")


def test_line_menu():
    print("menuconfig (line mode)")
    run("defconfig")
    script = "1\n1\n2\nb\n2\n1\n3\nb\ns\n"  # Pipeline/MUL=2, Memory/LINE=64, save
    result = run("menuconfig", stdin=script)
    check(result.returncode == 0, "line menu exits cleanly")
    out = run("show").stdout
    check("CONFIG_MUL_LATENCY = 2" in out, "line menu changed MUL_LATENCY")
    check("CONFIG_LINE_BYTES = 64" in out, "line menu changed LINE_BYTES")

    # "q" must leave the saved configuration alone
    run("set", "MUL_LATENCY=3", "LINE_BYTES=32")
    run("menuconfig", stdin="1\n1\n2\nb\nq\n")
    out = run("show").stdout
    check("CONFIG_MUL_LATENCY = 3" in out, "quit without saving keeps .config")


def test_curses_logic():
    """Drive the curses main loop with a mock screen (no terminal needed)."""
    print("menuconfig (curses logic, mocked screen)")
    import curses
    import importlib.util

    spec = importlib.util.spec_from_file_location("ares_kconfig", TOOL)
    tool = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tool)

    run("defconfig")
    cfg = tool.build_config()
    tool.resolve(cfg, tool.load_dot_config(DOT_CONFIG))

    class Screen:
        def __init__(self, keys):
            self.keys = list(keys)

        def keypad(self, flag):
            pass

        def getch(self):
            return self.keys.pop(0) if self.keys else ord("q")

    keys = [curses.KEY_DOWN, curses.KEY_ENTER,          # enter the Memory menu
            curses.KEY_ENTER,                            # cycle the LINE_BYTES choice
            ord("s")]                                    # save & exit
    result = tool._curses_main(Screen(keys), cfg, lambda *a: None,
                               lambda *a: None, lambda *a: "")
    check(result == tool.SAVE, "curses loop reports save")
    check(cfg.choices["LINE_BYTES"].selected == "LINE_BYTES_64",
          "curses loop cycles the choice to LINE_BYTES_64")

    keys = [curses.KEY_DOWN, curses.KEY_DOWN, ord("q")]
    result = tool._curses_main(Screen(keys), cfg, lambda *a: None,
                               lambda *a: None, lambda *a: "")
    check(result == tool.DISCARD, "curses loop reports discard on 'q'")


def test_curses_pty():
    print("menuconfig (curses, pty)")
    try:
        import pty
        pid, fd = pty.fork()
    except (ImportError, OSError) as exc:
        print("  skip : pty unavailable (%s)" % exc)
        return
    run("defconfig")
    if pid == 0:  # child
        os.environ["TERM"] = "xterm"
        os.environ.pop("ARES_KCONFIG_NOCURSES", None)
        os.execv(sys.executable, [sys.executable, TOOL, "menuconfig"])
        os._exit(127)  # not reached
    time.sleep(1.0)
    try:
        os.write(fd, b"q")  # quit without saving
    except OSError:
        print("  skip : pty write failed")
        os.kill(pid, 9)
        os.waitpid(pid, 0)
        return
    deadline = time.time() + 10
    status = None
    pty_open = True
    while time.time() < deadline:
        if pty_open and select.select([fd], [], [], 0.2)[0]:
            try:
                if not os.read(fd, 65536):
                    pty_open = False
            except OSError:
                pty_open = False
        if not pty_open:
            time.sleep(0.01)
        done, code = os.waitpid(pid, os.WNOHANG)
        if done == pid:
            status = code
            break
    if status is None:
        os.kill(pid, 9)
        os.waitpid(pid, 0)
        check(False, "curses menu did not exit")
        return
    check(os.WIFEXITED(status) and os.WEXITSTATUS(status) == 0,
          "curses menu exits cleanly on 'q'")


def main():
    try:
        test_defaults()
        test_set_and_range()
        test_defconfig_roundtrip()
        test_line_menu()
        test_curses_logic()
        test_curses_pty()
    finally:
        run("defconfig")
        run("savedefconfig")
    print()
    if FAILURES:
        print("FAILED: %d configuration test(s)" % len(FAILURES))
        return 1
    print("ALL TESTS PASSED: ares_kconfig (defaults, set, generation, defconfig "
          "round trip, line menu, curses logic)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
