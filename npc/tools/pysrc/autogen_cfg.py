#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Tool to convert Kconfig .config file into C, Verilog, and Scala headers.
"""

import sys
import os
import argparse
import re

# ==============================================================================
# Configuration & Constants
# ==============================================================================

# Requirement 5: Internal boolean toggle for Verilog prefix
ENABLE_VERILOG_PREFIX = False
VERILOG_PREFIX_STR = "ysyx_25050158_"

# File Headers
HEADER_COMMENT = "/** Auto-generated by autogen_cfg.py - DO NOT EDIT **/\n"

# C Header Guards
C_GUARD_START = "#ifndef __AUTOCONF_H__\n#define __AUTOCONF_H__\n"
C_GUARD_END = "#endif"

# Verilog Header Guards
V_GUARD_START = "`ifndef __AUTOCONF_VH__\n`define __AUTOCONF_VH__\n"
V_GUARD_END = "`endif"

# ==============================================================================
# Parsing Logic
# ==============================================================================

def parse_config_file(filepath):
    """
    Parses the .config file and returns a list of dictionaries.
    Format: [{'key': 'CONFIG_ABC', 'value': '123', 'is_set': True/False}, ...]
    """
    configs = []
    
    # Regex to capture KEY=VALUE
    line_pattern = re.compile(r'^\s*([A-Za-z0-9_]+)\s*=\s*(.*)\s*$')
    # Regex to capture "is not set" for Scala Boolean support
    not_set_pattern = re.compile(r'^#\s*(CONFIG_[A-Za-z0-9_]+)\s+is not set')

    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                
                if not line:
                    continue
                
                # Handle comments and "is not set"
                if line.startswith('#'):
                    # New Requirement 5: Need to extract "is not set" for Scala true/false
                    match = not_set_pattern.match(line)
                    if match:
                        configs.append({'key': match.group(1), 'value': 'n', 'is_set': False})
                    continue
                
                # Handle normal assignments
                match = line_pattern.match(line)
                if match:
                    key, value = match.groups()
                    configs.append({'key': key, 'value': value, 'is_set': True})
                    
    except FileNotFoundError:
        print(f"Error: Input file '{filepath}' not found.")
        sys.exit(1)
    except Exception as e:
        print(f"Error parsing file: {e}")
        sys.exit(1)

    return configs

# ==============================================================================
# C Header Generation
# ==============================================================================

def format_c_value(value):
    if value == 'y': return '1'
    if value == 'n': return '0'
    return value

def generate_c_header(configs):
    lines = []
    lines.append(HEADER_COMMENT)
    lines.append(C_GUARD_START)
    lines.append("") 

    for item in configs:
        # Original Req 7: Ignore "is not set" for C header
        if not item.get('is_set', True):
            continue
            
        key = item['key']
        val = format_c_value(item['value'])
        lines.append(f"#define {key} {val}")

    lines.append("") 
    lines.append(C_GUARD_END)
    lines.append("") 
    return "\n".join(lines)

# ==============================================================================
# Verilog Header Generation
# ==============================================================================

def format_verilog_value(value):
    if value.startswith("0x") and '"' not in value and "'" not in value:
        return "'h" + value[2:]
    if value == 'y': return '1'
    if value == 'n': return '0'
    return value

def generate_verilog_header(configs):
    lines = []
    lines.append(HEADER_COMMENT)
    lines.append(V_GUARD_START)
    lines.append("")

    for item in configs:
        # Original Req 7: Ignore "is not set" for Verilog header
        if not item.get('is_set', True):
            continue
            
        key = item['key']
        val = format_verilog_value(item['value'])
        
        final_key = key
        if ENABLE_VERILOG_PREFIX:
            final_key = VERILOG_PREFIX_STR + key
            
        lines.append(f"`define {final_key} {val}")

    lines.append("") 
    lines.append(V_GUARD_END)
    lines.append("") 
    return "\n".join(lines)

# ==============================================================================
# Scala File Generation
# ==============================================================================

def infer_scala_type_value(val_str):
    """
    Infers the appropriate Scala type and formats the value.
    Returns: (Scala_Type, Formatted_Value)
    """
    # 1. Booleans
    if val_str == 'y':
        return 'Boolean', 'true'
    if val_str == 'n':
        return 'Boolean', 'false'
        
    # 2. Strings (quoted in .config)
    if val_str.startswith('"') and val_str.endswith('"'):
        return 'String', val_str
        
    # 3. Hexadecimal Numbers
    if val_str.startswith('0x') or val_str.startswith('-0x'):
        try:
            num = int(val_str, 16)
            # Scala Int is 32-bit signed. Use Long (add 'L') if it exceeds bounds.
            if num > 0x7FFFFFFF or num < -0x80000000:
                return 'Long', val_str + 'L'
            else:
                return 'Int', val_str
        except ValueError:
            return 'String', f'"{val_str}"'
            
    # 4. Decimal Integers
    if val_str.isdigit() or (val_str.startswith('-') and val_str[1:].isdigit()):
        try:
            num = int(val_str)
            if num > 0x7FFFFFFF or num < -0x80000000:
                return 'Long', val_str + 'L'
            else:
                return 'Int', val_str
        except ValueError:
            pass
            
    # 5. Fallback for unhandled raw tokens
    return 'String', f'"{val_str}"'

def generate_scala_object(configs):
    lines = []
    lines.append(HEADER_COMMENT)
    lines.append("package npc")
    lines.append("")
    
    # New Req 4: Wrapped in object AutoConfig
    lines.append("object AutoConfig {")

    for item in configs:
        key = item['key']
        raw_val = item['value']
        
        # New Req 5: Explicit type definition and boolean conversion
        scala_type, scala_val = infer_scala_type_value(raw_val)
        lines.append(f"  val {key}: {scala_type} = {scala_val}")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)

# ==============================================================================
# File I/O
# ==============================================================================

def write_output_file(content, output_dir, filename):
    if not os.path.exists(output_dir):
        try:
            os.makedirs(output_dir)
            print(f"Created directory: {output_dir}")
        except OSError as e:
            print(f"Error creating directory {output_dir}: {e}")
            sys.exit(1)

    filepath = os.path.join(output_dir, filename)
    try:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Generated: {filepath}")
    except IOError as e:
        print(f"Error writing to {filepath}: {e}")
        sys.exit(1)

# ==============================================================================
# Main Execution
# ==============================================================================

def main():
    parser = argparse.ArgumentParser(description="Generate C, Verilog, and Scala headers from Kconfig .config file")
    
    parser.add_argument('-i', '--input', 
                        default='./.config',
                        help='Input .config file path (default: ./.config)')
    
    parser.add_argument('--out-v', 
                        default='build/vsrc/include/',
                        help='Output directory for .vh file (default: build/vsrc/include/)')
    
    parser.add_argument('--out-c', 
                        default='build/csrc/include/',
                        help='Output directory for .h file (default: build/csrc/include/)')
                        
    # New Req 2: Added Scala output path keeping the identical format
    parser.add_argument('--out-s', 
                        default='build/ssrc/include/',
                        help='Output directory for .scala file (default: build/ssrc/include/)')

    args = parser.parse_args()

    # 1. Parse Input
    print(f"Reading configuration from: {args.input}")
    configs = parse_config_file(args.input)

    # 2. Generate Contents
    c_content = generate_c_header(configs)
    v_content = generate_verilog_header(configs)
    s_content = generate_scala_object(configs)

    # 3. Write Files
    write_output_file(c_content, args.out_c, "autoconf.h")
    write_output_file(v_content, args.out_v, "autoconf.vh")
    write_output_file(s_content, args.out_s, "autoconf.scala")

if __name__ == "__main__":
    main()
