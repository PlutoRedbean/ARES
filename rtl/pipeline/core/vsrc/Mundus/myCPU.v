module myCPU(
  input         cpu_rst     ,
  input         cpu_clk     ,

  // Instruction-fetch request/response handshake
  output        irom_req_valid,
  output [31:0] irom_req_addr ,
  input         irom_req_ready,
  input         irom_rsp_valid,
  input  [31:0] irom_rsp_data ,
  output        irom_rsp_ready,
  output        irom_flush   ,

  output        perip_valid ,
  input         perip_ready ,
  input         perip_rvalid,
  output [31:0] perip_addr  ,
  output        perip_wen   ,
  output [ 1:0] perip_mask  ,
  output [31:0] perip_wdata ,
  input  [31:0] perip_rdata ,
  input         perip_idle  ,
  input         coh_inv_valid,
  input  [31:0] coh_inv_addr,
  input  [ 7:0] coh_epoch   ,
  input  [31:0] data_offset ,
  output        retire_valid,
  output [31:0] retire_pc   ,
  output [31:0] retire_pc_next,
  output        retire_rd_wen,
  output [ 4:0] retire_rd   ,
  output [31:0] retire_wdata,
  output        retire_is_ebreak
);

  Mundus Mundus (
    .clock                 (cpu_clk     ),
    .reset                 (cpu_rst     ),
    .io_irom_req_valid     (irom_req_valid),
    .io_irom_req_addr      (irom_req_addr ),
    .io_irom_req_ready     (irom_req_ready),
    .io_irom_rsp_valid     (irom_rsp_valid),
    .io_irom_rsp_data      (irom_rsp_data ),
    .io_irom_rsp_ready     (irom_rsp_ready),
    .io_irom_flush         (irom_flush   ),
    .io_perip_valid        (perip_valid ),
    .io_perip_ready        (perip_ready ),
    .io_perip_rvalid       (perip_rvalid),
    .io_perip_addr         (perip_addr  ),     
    .io_perip_wen          (perip_wen   ),      
    .io_perip_mask         (perip_mask  ),     
    .io_perip_wdata        (perip_wdata ),    
    .io_perip_rdata        (perip_rdata ),    
    .io_perip_idle         (perip_idle  ),
    .io_coh_inv_valid      (coh_inv_valid),
    .io_coh_inv_addr       (coh_inv_addr),
    .io_coh_epoch          (coh_epoch   ),
    .io_data_offset        (data_offset ),
    .io_retire_valid       (retire_valid),
    .io_retire_pc          (retire_pc   ),
    .io_retire_pc_next     (retire_pc_next),
    .io_retire_rd_wen      (retire_rd_wen),
    .io_retire_rd          (retire_rd   ),
    .io_retire_wdata       (retire_wdata),
    .io_retire_is_ebreak   (retire_is_ebreak)
  );
endmodule
