//=============================================================================
// ARES pipeline SoC - Pango-inferred 256 KiB DRAM
//-----------------------------------------------------------------------------
// Replaces soc/ip/BRAM.v (the Verilator/DPI model) in the PDS synthesis file
// list.  Same module name and port list so bram_driver.v is unchanged.
//
//   * 65536 x 32-bit simple dual-port RAM
//   * byte write enables (wea[3:0])
//   * two-cycle read latency: BRAM array + output register, matching the DPI
//     model and the response pipeline in perip_bridge.sv
//   * initialized from build/pipeline/dram.hex (generated by
//     scripts/pipeline_image.py)
//
// Verilog-2001; inferred BRAM attributes are understood by Pango's Synplify
// front end (syn_ramstyle) and ignored by other tools.
//=============================================================================
`timescale 1ns / 1ps

module BRAM #(
    parameter DRAM_INIT_FILE = "build/pipeline/dram.hex"
) (
    input  wire        clka,
    input  wire [15:0] addra,
    input  wire [ 3:0] wea,
    input  wire [31:0] dina,
    input  wire        clkb,
    input  wire [15:0] addrb,
    output wire [31:0] doutb
);
    (* syn_ramstyle = "block_ram", ram_style = "block" *)
    reg [31:0] mem [0:65535];

    reg [31:0] rdata;
    reg [31:0] doutb_r;

    initial begin
        $readmemh(DRAM_INIT_FILE, mem);
    end

    // Byte-enabled write port.
    always @(posedge clka) begin
        if (wea[0]) mem[addra][ 7: 0] <= dina[ 7: 0];
        if (wea[1]) mem[addra][15: 8] <= dina[15: 8];
        if (wea[2]) mem[addra][23:16] <= dina[23:16];
        if (wea[3]) mem[addra][31:24] <= dina[31:24];
    end

    // Read port + output register (two-cycle latency).
    always @(posedge clkb) begin
        rdata   <= mem[addrb];
        doutb_r <= rdata;
    end

    assign doutb = doutb_r;
endmodule
