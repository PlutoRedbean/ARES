//=============================================================================
// ARES pipeline SoC - Pango-inferred per-hart DRAM
//-----------------------------------------------------------------------------
// Replaces soc/ip/BRAM.v (the Verilator/DPI model) in the PDS synthesis file
// list.  Same module name and port list so bram_driver.sv is unchanged.
//
//   * 2**DRAM_AW x 32-bit simple dual-port RAM
//   * byte write enables (wea[3:0])
//   * two-cycle read latency: BRAM array + output register, matching the DPI
//     model and the response pipeline in perip_bridge.sv
//   * initialized from DRAM_INIT_FILE (generated by scripts/pipeline_image.py)
//
// DRAM_AW is the word-address width:
//   16 = 65536 x 32-bit = 256 KiB  (single-hart profile, ares-linker.ld)
//   13 =  8192 x 32-bit =  32 KiB  (AMP profile, ares-linker-mc.ld)
//
// Why 13 is enough for the AMP profile: the linker gives every hart a private
// 32 KiB window at 0x8010_0000 + hart*0x8000, and the image replicates the
// 32 KiB data region at every window.  A hart's DRAM instance therefore only
// ever needs the low 13 word-address bits -- addr[16:15] is the hart index,
// which selects a *different physical BRAM* and must be dropped.  Slicing
// addra/addrb with DRAM_AW does that, and it is what turns the per-hart
// memory from 64 DRAM36K into 8 (256 of 415 on the device -> 32).
//
// Verilog-2001; inferred BRAM attributes are understood by Pango's Synplify
// front end (syn_ramstyle) and ignored by other tools.
//=============================================================================
`timescale 1ns / 1ps

module BRAM #(
    parameter integer DRAM_AW        = 16,
    parameter         DRAM_INIT_FILE = "build/pipeline/dram.hex"
) (
    input  wire        clka,
    input  wire [15:0] addra,
    input  wire [ 3:0] wea,
    input  wire [31:0] dina,
    input  wire        clkb,
    input  wire [15:0] addrb,
    output wire [31:0] doutb
);
    (* syn_ramstyle = "block_ram", ram_style = "block" *)
    reg [31:0] mem [0:(1 << DRAM_AW) - 1];

    // Word index inside this hart's window (drops the hart offset).
    wire [DRAM_AW-1:0] wa = addra[DRAM_AW-1:0];
    wire [DRAM_AW-1:0] ra = addrb[DRAM_AW-1:0];

    reg [31:0] rdata;
    reg [31:0] doutb_r;

    initial begin
        $readmemh(DRAM_INIT_FILE, mem);
    end

    // Byte-enabled write port.
    always @(posedge clka) begin
        if (wea[0]) mem[wa][ 7: 0] <= dina[ 7: 0];
        if (wea[1]) mem[wa][15: 8] <= dina[15: 8];
        if (wea[2]) mem[wa][23:16] <= dina[23:16];
        if (wea[3]) mem[wa][31:24] <= dina[31:24];
    end

    // Read port + output register (two-cycle latency).
    always @(posedge clkb) begin
        rdata   <= mem[ra];
        doutb_r <= rdata;
    end

    assign doutb = doutb_r;
endmodule
